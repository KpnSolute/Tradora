/**
 * Mock model server — an OpenAI/OpenRouter-compatible chat-completions endpoint
 * for exercising the AI rule builder's success cases without any API key.
 *
 *   node scripts/mock-model-server.mjs            # http://127.0.0.1:4319/v1
 *   MOCK_MODEL_PORT=5000 node scripts/mock-model-server.mjs
 *
 * Point the API at it with:
 *   RULE_BUILDER_PROVIDER=mock
 *   MOCK_MODEL_BASE_URL=http://127.0.0.1:4319/v1
 *   MOCK_MODEL_API_KEY=test-key-not-secret
 *
 * Scenario selection, first match wins:
 *   1. `?scenario=<name>` query parameter
 *   2. `x-mock-scenario` request header
 *   3. `[scenario:<name>]` anywhere in the last user message
 *   4. "plain"
 *
 * Scenarios: plain, fenced, sse, parts, output_text, empty, reject_response_format,
 * invalid_json, invalid_rule, server_error, no_key.
 *
 * GET /__stats returns the request count and per-scenario hit counts so a test can
 * prove a retry actually happened.
 */
import { createServer } from "node:http";
import { fileURLToPath } from "node:url";
import { realpathSync } from "node:fs";

const SYMBOLS = [
  "BTC-USDT", "ETH-USDT", "SOL-USDT", "XRP-USDT", "DOGE-USDT", "ADA-USDT",
  "AVAX-USDT", "LINK-USDT", "DOT-USDT", "MATIC-USDT", "LTC-USDT", "BCH-USDT",
];

const SCENARIOS = [
  "plain", "fenced", "sse", "parts", "output_text", "empty",
  "reject_response_format", "invalid_json", "invalid_rule", "server_error", "no_key",
];

function lastUserText(body) {
  const messages = Array.isArray(body?.messages) ? body.messages : [];
  const last = [...messages].reverse().find(m => m?.role === "user");
  if (typeof last?.content === "string") return last.content;
  if (Array.isArray(last?.content)) {
    return last.content.map(p => (typeof p?.text === "string" ? p.text : "")).join(" ");
  }
  return "";
}

function scenarioFor(req, body) {
  const url = new URL(req.url ?? "/", "http://127.0.0.1");
  const fromQuery = url.searchParams.get("scenario");
  if (fromQuery) return fromQuery.toLowerCase();
  const fromHeader = req.headers["x-mock-scenario"];
  if (typeof fromHeader === "string" && fromHeader) return fromHeader.toLowerCase();
  const marker = lastUserText(body).match(/\[scenario:([a-z_]+)\]/i);
  if (marker) return marker[1].toLowerCase();
  return "plain";
}

/** Deterministic rule extraction so assertions can be exact. */
function buildRule(text) {
  const upper = text.toUpperCase();
  const symbol = SYMBOLS.find(s => upper.includes(s)) ?? "BTC-USDT";
  const money = text.match(/(?:above|below|over|under|at|reaches?|drops? to|rises? to)\s*\$?(\d+(?:\.\d+)?)/i);
  const qtyMatch = text.match(/(?:buy|sell|long|short)\s+(\d+(?:\.\d+)?)/i);
  return {
    symbol,
    condition: /(below|under|drops?|falls?|lte|≤)/i.test(text) ? "lte" : "gte",
    triggerPrice: money ? Number(money[1]) : 65000,
    side: /(sell|short|exit|close)/i.test(text) ? "sell" : "buy",
    quantity: qtyMatch ? Number(qtyMatch[1]) : 1,
    orderType: /limit/i.test(text) ? "limit" : "market",
    limitPrice: /limit/i.test(text) ? (money ? Number(money[1]) : 65000) : null,
    broker: "paper",
  };
}

function draftJson(text) {
  return JSON.stringify({
    rule: buildRule(text),
    explanation: "Mock draft generated by the local mock model server.",
    warnings: [],
  });
}

function chatEnvelope(body, content) {
  return {
    id: "chatcmpl-mock",
    object: "chat.completion",
    created: Math.floor(Date.now() / 1000),
    model: body?.model ?? "mock/rule-draft",
    choices: [{ index: 0, message: { role: "assistant", content }, finish_reason: "stop" }],
    usage: { prompt_tokens: 100, completion_tokens: 80, total_tokens: 180 },
  };
}

function sendJson(res, status, payload) {
  const text = JSON.stringify(payload);
  res.writeHead(status, { "content-type": "application/json; charset=utf-8", "content-length": Buffer.byteLength(text) });
  res.end(text);
}

/**
 * Start the mock server. `port: 0` picks a free port, which is what the test
 * harness uses so parallel runs cannot collide.
 */
export function startMockModelServer({ port = Number(process.env.MOCK_MODEL_PORT) || 4319, quiet = false } = {}) {
  const stats = { requests: 0, scenarios: {}, bodies: [] };

  const server = createServer((req, res) => {
    const url = new URL(req.url ?? "/", "http://127.0.0.1");

    if (url.pathname.endsWith("/__stats")) {
      sendJson(res, 200, { requests: stats.requests, scenarios: stats.scenarios, bodies: stats.bodies.slice(-5) });
      return;
    }
    if (url.pathname.endsWith("/__reset") && req.method === "POST") {
      stats.requests = 0;
      stats.scenarios = {};
      stats.bodies = [];
      sendJson(res, 200, { ok: true });
      return;
    }

    let raw = "";
    req.on("data", chunk => { raw += chunk; });
    req.on("end", () => {
      let body = null;
      try {
        body = raw ? JSON.parse(raw) : null;
      } catch {
        sendJson(res, 400, { error: { message: "Mock: request body was not JSON" } });
        return;
      }

      const scenario = scenarioFor(req, body);
      stats.requests += 1;
      stats.scenarios[scenario] = (stats.scenarios[scenario] ?? 0) + 1;
      stats.bodies.push({ scenario, model: body?.model, responseFormat: Boolean(body?.response_format) });
      if (!quiet) console.log(`[mock-model] #${stats.requests} scenario=${scenario} model=${body?.model}`);

      if (!/^Bearer\s+\S+/.test(String(req.headers.authorization ?? "")) || scenario === "no_key") {
        sendJson(res, 401, { error: { message: "Mock: missing or invalid API key", code: "invalid_api_key" } });
        return;
      }

      const text = lastUserText(body);
      const content = draftJson(text);

      switch (scenario) {
        case "reject_response_format":
          if (body?.response_format) {
            sendJson(res, 400, {
              error: { message: "response_format 'json_object' is not supported by this model", code: "invalid_request" },
            });
            return;
          }
          sendJson(res, 200, chatEnvelope(body, content));
          return;

        case "server_error":
          sendJson(res, 500, { error: { message: "mock upstream exploded" } });
          return;

        case "invalid_json":
          sendJson(res, 200, chatEnvelope(body, "Sure! Buy when it dips below the trigger."));
          return;

        case "invalid_rule": {
          const broken = JSON.parse(content);
          broken.rule.quantity = -1;
          sendJson(res, 200, chatEnvelope(body, JSON.stringify(broken)));
          return;
        }

        case "empty":
          sendJson(res, 200, { id: "chatcmpl-mock", choices: [{ index: 0, message: { role: "assistant", content: "" } }] });
          return;

        case "fenced":
          sendJson(res, 200, chatEnvelope(body, "```json\n" + content + "\n```"));
          return;

        case "parts":
          sendJson(res, 200, {
            id: "chatcmpl-mock",
            choices: [{ index: 0, message: { role: "assistant", content: [{ type: "text", text: content }] } }],
          });
          return;

        case "output_text":
          sendJson(res, 200, { id: "chatcmpl-mock", output_text: content });
          return;

        case "sse": {
          res.writeHead(200, {
            "content-type": "text/event-stream; charset=utf-8",
            "cache-control": "no-cache",
            connection: "keep-alive",
          });
          const mid = Math.floor(content.length / 2);
          for (const piece of [content.slice(0, mid), content.slice(mid)]) {
            res.write(`data: ${JSON.stringify({ choices: [{ index: 0, delta: { content: piece } }] })}\n\n`);
          }
          res.write("data: [DONE]\n\n");
          res.end();
          return;
        }

        case "plain":
        default:
          sendJson(res, 200, chatEnvelope(body, content));
          return;
      }
    });
  });

  return new Promise((resolve, reject) => {
    server.once("error", reject);
    server.listen(port, "127.0.0.1", () => {
      const actual = server.address().port;
      resolve({
        server,
        port: actual,
        url: `http://127.0.0.1:${actual}/v1`,
        stats,
        scenarios: SCENARIOS,
        close: () => new Promise(done => server.close(() => done())),
      });
    });
  });
}

const invokedDirectly = process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const started = await startMockModelServer();
  console.log(`Mock model server ready at ${started.url}`);
  console.log(`Scenarios: ${SCENARIOS.join(", ")}`);
  console.log("Use RULE_BUILDER_PROVIDER=mock MOCK_MODEL_BASE_URL=" + started.url + " MOCK_MODEL_API_KEY=test-key-not-secret");
}
